export interface MeanElements {
  a: number;
  e: number;
  i: number;
  node: number;
  peri: number;
  m0: number;
  period: number;
}

/**
 * Mean orbital elements from JPL Horizons osculating elements sampled over 2020–2040.
 *
 *   - mean motion and epoch phase: least-squares line through the unwrapped mean
 *     longitude L = Ω + ω + M, so positions stay right for decades;
 *   - a, e: averages over the window;
 *   - i, Ω, ω: values at the middle of the window (≈ 2030).
 *
 * Output is SI / radians, with the mean anomaly referred to J2000 (t = 0).
 */
export function buildSolarElements(): Record<string, MeanElements> {
  const out: Record<string, MeanElements> = {};
  const J2000 = 2451545.0;
  for (const [key] of HORIZONS_BODIES) {
    const text = readFileSync(rawPath(`sol2/${key}.txt`), 'utf8');
    const block = /\$\$SOE\s*([\s\S]*?)\$\$EOE/.exec(text);
    if (!block) throw new Error(`Horizons output for ${key} has no ephemeris block: ${text.slice(0, 300)}`);
    // Columns: JDTDB, Calendar, EC, QR, IN, OM, W, Tp, N, MA, TA, A, AD, PR   (km, s, degrees)
    const rows = block[1]!.trim().split('\n').map((line) => line.split(',').map((c) => c.trim()));
    if (rows.length < 100) throw new Error(`Horizons output for ${key} is too short (${rows.length} rows)`);
    const t: number[] = [];
    const L: number[] = [];
    let sumA = 0;
    let sumE = 0;
    let prev = 0;
    rows.forEach((r, k) => {
      const jd = Number(r[0]);
      const [ec, , , om, w, , n, ma, , a] = r.slice(2).map(Number);
      if (![jd, ec, om, w, n, ma, a].every((v) => Number.isFinite(v))) throw new Error(`Bad Horizons row for ${key}: ${r.join(',').slice(0, 120)}`);
      const sec = (jd - J2000) * 86400;
      let l = om! + w! + ma!;
      if (k > 0) {
        // Unwrap: predict from the previous sample with the osculating mean motion, then snap to the nearest turn.
        const predicted = prev + n! * (sec - t[k - 1]!);
        l += 360 * Math.round((predicted - l) / 360);
      }
      prev = l;
      t.push(sec);
      L.push(l);
      sumA += a!;
      sumE += ec!;
    });
    // Least-squares fit L(t) = L0 + rate·t (centred for numerical conditioning).
    const n = t.length;
    const tm = t.reduce((s, v) => s + v, 0) / n;
    const lm = L.reduce((s, v) => s + v, 0) / n;
    let sxx = 0;
    let sxy = 0;
    for (let k = 0; k < n; k++) {
      sxx += (t[k]! - tm) * (t[k]! - tm);
      sxy += (t[k]! - tm) * (L[k]! - lm);
    }
    const rate = sxy / sxx; // deg / s
    const l0 = lm - rate * tm; // mean longitude at J2000, deg
    const mid = rows[Math.floor(n / 2)]!.slice(2).map(Number);
    const inc = mid[2]!;
    const om = mid[3]!;
    const w = mid[4]!;
    const m0 = (((l0 - om - w) % 360) + 360) % 360;
    out[key] = { a: (sumA / n) * 1000, e: sumE / n, i: inc * DEG, node: om * DEG, peri: w * DEG, m0: m0 * DEG, period: 360 / rate };
  }
  const dest = join(here, '..', '..', '..', 'src', 'universe', 'data', 'solarElements.json');
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(
    dest,
    JSON.stringify({ _source: 'JPL Horizons (ssd.jpl.nasa.gov, DE441): mean elements fitted to osculating elements over 2020-2040, ecliptic of J2000; SI units, radians, mean anomaly referred to J2000. Generated by scripts/build-catalogs - do not edit.', bodies: out }, null, 1) + '\n',
  );
  console.info(`  ✓ solar system: ${Object.keys(out).length} bodies → src/universe/data/solarElements.json`);
  return out;
}

/** Constellation stick figures: Hipparcos ids → star position codes (so lines stay attached to the real stars in 3D). */
export function buildConstellations(store: StarStore): { file: { file: string; bytes: number; count: number }; missing: number } {
  const sky = JSON.parse(readFileSync(rawPath('names/stellarium_modern.json'), 'utf8')) as {
    constellations: Array<{ id: string; lines: number[][]; common_name: { english?: string; native?: string } }>;
  };
  let missing = 0;
  const out = sky.constellations.map((con) => {
    const abbr = con.id.split(' ').pop()!;
    const lines: number[][][] = [];
    for (const line of con.lines) {
      const pts: number[][] = [];
      for (const hip of line) {
        const idx = store.byHip.get(hip);
        if (idx === undefined) {
          missing++;
          // Break the polyline rather than connect across a missing star.
          if (pts.length > 1) lines.push(pts.splice(0));
          else pts.length = 0;
          continue;
        }
        pts.push([qStarRa(store.ra[idx]!), qStarDec(store.dec[idx]!), qStarDist(store.dist[idx]!)]);
      }
      if (pts.length > 1) lines.push(pts);
    }
    return { abbr, name: CONSTELLATIONS[abbr]?.[0] ?? con.common_name.native ?? abbr, english: con.common_name.english ?? '', lines };
  });
  const bytes = zlibSync(new TextEncoder().encode(JSON.stringify(out)), { level: 9 });
  writeFileSync(join(OUT_DIR, 'constellations.bin'), bytes);
  console.info(`  ✓ constellations: ${out.length} figures (${missing} line vertices without a catalogued star were dropped)`);
  return { file: { file: 'constellations.bin', bytes: bytes.byteLength, count: out.length }, missing };
}

// ------------------------------------------------------------ large-scale structure

/** 2MRS flux limit (Ks) and the pseudo-r equivalent used by the procedural suppression rule. */
export const TWOMRS_K_LIMIT = 11.75;
/** SDSS main galaxy sample limit (Petrosian r, extinction corrected). */
export const SDSS_R_LIMIT = 17.77;
export const LSS_GRID_N = 96;
export const LSS_GRID_HALF_MPC = 240;
export const MASK_W = 720;
export const MASK_H = 360;

/** Fraction of the K-band luminosity function (above M_K = −20.5) that 2MRS can see at distance d. */
function twoMrsCompleteness(dMpc: number): number {
  // Schechter K-band LF (Kochanek et al. 2001), rescaled to h = 0.6766: M* = −24.25, α = −1.09.
  const mStar = -24.25;
  const alpha = -1.09;
  const lum = (m: number): number => Math.pow(10, -0.4 * (m - mStar));
  const integral = (lMin: number): number => {
    // ∫_{lMin}^{∞} x^α e^{−x} dx by log-space trapezoid.
    let s = 0;
    const n = 200;
    const a = Math.log(lMin);
    const b = Math.log(60);
    for (let i = 0; i <= n; i++) {
      const x = Math.exp(a + ((b - a) * i) / n);
      s += Math.pow(x, alpha + 1) * Math.exp(-x) * (i === 0 || i === n ? 0.5 : 1);
    }
    return (s * (b - a)) / n;
  };
  const floor = lum(-20.5);
  const mLimit = TWOMRS_K_LIMIT - 5 * Math.log10(Math.max(dMpc, 0.1) * 1e5);
  return Math.min(1, integral(Math.max(floor, lum(mLimit))) / integral(floor));
}

export function buildLss(sdss: { ra: Uint32Array; dec: Uint32Array; z: Uint16Array; mag: Uint8Array; count: number }): { file: { file: string; bytes: number }; stats: Record<string, number> } {
  // ---- (a) density of the local universe from 2MRS, corrected for the survey's flux limit.
  const N = LSS_GRID_N;
  const half = LSS_GRID_HALF_MPC;
  const cell = (2 * half) / N;
  const grid = new Float32Array(N * N * N);
  const t = readVizierTsv(rawPath('gal/2mrs.tsv'));
  const c = { ra: t.col('RAJ2000'), dec: t.col('DEJ2000'), cz: t.col('cz') };
  let used = 0;
  for (const r of t.rows) {
    const ra = num(r[c.ra]);
    const dec = num(r[c.dec]);
    const v = localGroupVelocity(num(r[c.cz]), ra, dec);
    if (!(v > 150)) continue;
    const d = comovingDistanceMpc(v / 299_792.458);
    if (d > half * 1.7) continue;
    const u = raDecToUnit(ra, dec);
    const w = Math.min(40, 1 / Math.max(1e-3, twoMrsCompleteness(d)));
    // Cloud-in-cell deposit.
    const gx = (u.x * d + half) / cell - 0.5;
    const gy = (u.y * d + half) / cell - 0.5;
    const gz = (u.z * d + half) / cell - 0.5;
    const ix = Math.floor(gx);
    const iy = Math.floor(gy);
    const iz = Math.floor(gz);
    for (let dz = 0; dz < 2; dz++) {
      for (let dy = 0; dy < 2; dy++) {
        for (let dx = 0; dx < 2; dx++) {
          const x = ix + dx;
          const y = iy + dy;
          const z = iz + dz;
          if (x < 0 || y < 0 || z < 0 || x >= N || y >= N || z >= N) continue;
          grid[(z * N + y) * N + x]! += w * (dx ? gx - ix : 1 - (gx - ix)) * (dy ? gy - iy : 1 - (gy - iy)) * (dz ? gz - iz : 1 - (gz - iz));
        }
      }
    }
    used++;
  }
  // Separable Gaussian smoothing (σ = 1 cell ≈ 5 Mpc) to turn discrete galaxies into a continuous field.
  const kernel = [0.06136, 0.24477, 0.38774, 0.24477, 0.06136];
  const tmp = new Float32Array(grid.length);
  const blur = (src: Float32Array, dst: Float32Array, axis: 0 | 1 | 2): void => {
    const stride = axis === 0 ? 1 : axis === 1 ? N : N * N;
    for (let z = 0; z < N; z++) {
      for (let y = 0; y < N; y++) {
        for (let x = 0; x < N; x++) {
          const idx = (z * N + y) * N + x;
          const pos = axis === 0 ? x : axis === 1 ? y : z;
          let s = 0;
          for (let k = -2; k <= 2; k++) {
            const j = Math.min(N - 1, Math.max(0, pos + k));
            s += src[idx + (j - pos) * stride]! * kernel[k + 2]!;
          }
          dst[idx] = s;
        }
      }
    }
  };
  blur(grid, tmp, 0);
  blur(tmp, grid, 1);
  blur(grid, tmp, 2);
  // Normalise by the mean density inside the well-sampled sphere (r < 150 Mpc).
  let sum = 0;
  let cnt = 0;
  for (let z = 0; z < N; z++) {
    for (let y = 0; y < N; y++) {
      for (let x = 0; x < N; x++) {
        const r = Math.hypot((x + 0.5) * cell - half, (y + 0.5) * cell - half, (z + 0.5) * cell - half);
        if (r < 150) {
          sum += tmp[(z * N + y) * N + x]!;
          cnt++;
        }
      }
    }
  }
  const mean = sum / cnt;
  const gridBytes = new Uint8Array(grid.length);
  // Stored as 96 + 16·log2(ρ/ρ̄), clamped: 4.4 % steps over 0.016 … 980 × mean density.
  for (let i = 0; i < grid.length; i++) gridBytes[i] = Math.max(0, Math.min(255, Math.round(96 + 16 * Math.log2(Math.max(tmp[i]! / mean, 1e-3)))));

  // ---- (b) SDSS main-sample footprint on an equal-area (RA × sin Dec) grid.
  const counts = new Uint16Array(MASK_W * MASK_H);
  for (let i = 0; i < sdss.count; i++) {
    const mag = sdss.mag[i]! === 255 ? 99 : sdss.mag[i]! / 10 - 1.5;
    if (mag > SDSS_R_LIMIT || dqRedshift(sdss.z[i]!) > 0.3) continue;
    const ra = dqNameRa(sdss.ra[i]!);
    const dec = dqNameDec(sdss.dec[i]!);
    const mx = Math.min(MASK_W - 1, Math.floor((ra / 360) * MASK_W));
    const my = Math.min(MASK_H - 1, Math.floor(((Math.sin(dec * DEG) + 1) / 2) * MASK_H));
    if (counts[my * MASK_W + mx]! < 65535) counts[my * MASK_W + mx]!++;
  }
  // Each cell is 0.159 deg²; the main sample has ~90 galaxies/deg², so ≥ 4 means "surveyed".
  const mask = new Uint8Array(MASK_W * MASK_H);
  let covered = 0;
  for (let i = 0; i < mask.length; i++) {
    if (counts[i]! >= 4) {
      mask[i] = 1;
      covered++;
    }
  }

  const header = new Uint8Array(24);
  const view = new DataView(header.buffer);
  view.setUint32(0, 0x3153534c, true); // 'LSS1'
  view.setUint32(4, N, true);
  view.setFloat32(8, half, true);
  view.setUint32(12, MASK_W, true);
  view.setUint32(16, MASK_H, true);
  const payload = new Uint8Array(24 + gridBytes.length + mask.length);
  payload.set(header, 0);
  payload.set(gridBytes, 24);
  payload.set(mask, 24 + gridBytes.length);
  const bytes = zlibSync(payload, { level: 9, mem: 12 });
  writeFileSync(join(OUT_DIR, 'lss.bin'), bytes);
  const sqDeg = (covered / mask.length) * 41_253;
  console.info(`  ✓ large-scale structure: ${N}³ density grid from ${used} 2MRS galaxies; SDSS footprint ≈ ${sqDeg.toFixed(0)} deg² (${(bytes.byteLength / 1e3).toFixed(0)} kB)`);
  return { file: { file: 'lss.bin', bytes: bytes.byteLength }, stats: { lssGalaxiesUsed: used, sdssFootprintSqDeg: Math.round(sqDeg) } };
}

/** Galactic latitude in degrees (2MRS avoids the plane of the Milky Way). */
export function galacticLatitude(raDeg: number, decDeg: number): number {
  const g = mat3MulV(ICRS_TO_GAL, raDecToUnit(raDeg, decDeg));
  return Math.asin(Math.max(-1, Math.min(1, g.z))) / DEG;
}
