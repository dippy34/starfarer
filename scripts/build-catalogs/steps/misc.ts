/**
 * Smaller build products:
 *   - Solar System orbital elements from JPL Horizons → src/universe/data/solarElements.json
 *     (bundled with the app so the Solar System works before any data is fetched)
 *   - Constellation figures (Stellarium "modern" sky culture) resolved to real star positions
 *   - Large-scale-structure data used to blend procedural galaxies with the real ones:
 *       · a density grid of the local universe estimated from 2MRS
 *       · the SDSS main-sample sky coverage mask
 */
